    NAMES = ISO.transform_values(&:last).freeze

    ALPHA3 = ISO.to_h { |code, (alpha3, _name)| [ alpha3, code ] }.freeze

    # Unknown codes fall back to the code itself rather than raising: a rule for
    # a country nobody has added a name for should still render.
    def self.name(code) = NAMES.fetch(code.to_s.upcase, code.to_s)

    # Heading form: drops the leading article so "the United Kingdom" reads as
    # "United Kingdom" in a list or a chip. Deliberately does not call capitalize
    # — the names are already correctly cased, and capitalize would downcase the
    # rest of the string, turning "United Kingdom" into "United kingdom".
    def self.title(code) = name(code).delete_prefix("the ")

    # Every code, ordered the way somebody reading a list of 249 of them expects.
    # Sorted on the title so the article does not bury half the list under T, and
    # with accents stripped for the comparison only — a plain sort puts Côte
    # d'Ivoire and Åland after Zimbabwe, which is where nobody will look.
    def self.all
      ISO.keys.sort_by { |code| title(code).unicode_normalize(:nfd).gsub(/\p{Mn}/, "") }
    end

    # nil rather than a guess for anything outside the standard. The MRZ carries
    # codes that are not countries at all — stateless, refugee, United Nations —
    # and inventing an issuing country for one of those is worse than leaving the
    # field for a person to fill in.
    def self.from_alpha3(code) = ALPHA3[code.to_s.upcase]
  end
